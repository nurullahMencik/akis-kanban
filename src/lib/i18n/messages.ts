export const dictionaries = { tr, en } as const;
export type Locale = keyof typeof dictionaries;
export const LOCALES: readonly Locale[] = ["tr", "en"];

export function format(
  messages: Messages,
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let message: string = messages[key] ?? tr[key];
  if (message.includes("|") && params && typeof params.count === "number" && key !== "board.defaultColumns") {
    const [one, other] = message.split("|");
    const rule = new Intl.PluralRules(locale).select(params.count);
    message = (rule === "one" ? one : other) ?? message;
  }
  if (!params) return message;
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name]),
  );
}
